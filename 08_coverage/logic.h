#pragma once

namespace logic {

// 【坑 1】短路求值: a > 0 为假时, b > 0 根本不会被求值
// 只测 (1,1) 和 (-1,1) 就能让这两行都执行到(行覆盖 100%),
// 但 b > 0 的"假"分支从来没走过 -> 分支覆盖 < 100%
bool can_drive(int age, bool has_license);

// 【坑 2】多路分支: 少测一个区间, 行覆盖照样可能是 100%
int classify(int score);

// 对照组: 没有分支的函数, 覆盖率和上面一样容易满
int square(int x);

}  // namespace logic
